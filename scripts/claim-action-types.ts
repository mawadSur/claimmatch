/**
 * Owner-apply SQL for lawsuits.claim_action_type (0051).
 *
 *   npx tsx scripts/claim-action-types.ts
 *
 * Do not apply this SQL from CI or this script. The owner reviews
 * supabase/owner-apply/claim-action-types.sql in the Supabase SQL editor.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CLAIM_ACTION_CATALOG, type ClaimActionCatalogRow } from '../src/lib/claim-action-catalog';

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function actionJson(row: ClaimActionCatalogRow): string {
  const extra: Record<string, unknown> = {};
  if (row.action_type === 'mail_in' && row.claim_url) extra.form_url = row.claim_url;
  if (row.action_type === 'mail_in') extra.postmark = true;
  return sqlString(JSON.stringify(extra));
}

export function claimActionTypesSql(rows: readonly ClaimActionCatalogRow[] = CLAIM_ACTION_CATALOG): string {
  const header = `-- Owner-apply only. Do not run from CI or this repo's scripts.
-- Sets lawsuits.claim_action_type / claim_action for the 122 open published
-- catalog rows from the 2026-11 claim-site audit (see docs/claim-link-out-audit.md).
-- Requires migration 0051. Does not approve filing specs or policies.
-- Generated by scripts/claim-action-types.ts.

`;
  const blocks = rows.map((row) => {
    return `update public.lawsuits
   set claim_action_type = ${sqlString(row.action_type)},
       claim_action = ${actionJson(row)}::jsonb
 where slug = ${sqlString(row.slug)};
`;
  });
  const counts = rows.reduce<Record<string, number>>((acc, row) => {
    acc[row.action_type] = (acc[row.action_type] ?? 0) + 1;
    return acc;
  }, {});
  const footer = `
-- Expected counts: ${Object.entries(counts)
    .map(([k, v]) => `${k}=${v}`)
    .join(', ')}.
`;
  return header + blocks.join('\n') + footer;
}

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../supabase/owner-apply/claim-action-types.sql');
if (process.argv[1] && process.argv[1].includes('claim-action-types')) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, claimActionTypesSql());
  console.log(`wrote ${out} (${CLAIM_ACTION_CATALOG.length} rows)`);
}
